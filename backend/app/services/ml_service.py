import os
import math
import logging
from pathlib import Path
from typing import Dict, Any, Tuple, Optional
import pandas as pd
import numpy as np
import joblib

from backend.app.config import settings

logger = logging.getLogger(__name__)

FEATURE_NAMES = ["PM2.5", "PM10", "NO2", "CO", "SO2", "O3"]

STATUS_COLORS = {
    "Satisfactory": "#10b981",  # Green
    "Moderate": "#f59e0b",      # Amber
    "Poor": "#f97316",          # Orange
    "Very Poor": "#ef4444",      # Red
    "Severe": "#7f1d1d",         # Deep Red/Burgundy
}

HEALTH_GUIDANCE = {
    "Satisfactory": "Air quality is generally acceptable. Minimal impact on healthy individuals. Outdoor activities can proceed normally.",
    "Moderate": "Acceptable air quality for most. Unusually sensitive individuals may experience minor breathing discomfort; consider moderating prolonged outdoor exertion.",
    "Poor": "Air quality may cause breathing discomfort to people with lung disease, asthma, and heart conditions. Active children and adults should reduce prolonged outdoor exertion.",
    "Very Poor": "Respiratory illness likely upon prolonged exposure. Sensitive groups should remain indoors. General public should substantially limit outdoor activities.",
    "Severe": "Emergency conditions. Serious health risks to entire population. Avoid all outdoor physical activity, keep windows sealed, and operate HEPA air purifiers.",
}

REGULATORY_DISCLAIMER = (
    "Note: This classification is generated by a trained Scikit-learn machine-learning model based on input concentrations. "
    "It is distinct from official regulatory Multi-Pollutant Index (AQI) calculations (e.g., US EPA or CPCB sub-index algorithms), "
    "which incorporate specific breakpoint formulas and mandated averaging periods."
)

class MLService:
    _instance = None
    _model = None
    _model_path_used = None
    _model_type = "None"
    _classes = ["Moderate", "Poor", "Satisfactory", "Severe", "Very Poor"]
    _is_fallback = False

    def __new__(cls):
        if cls._instance is None:
            cls._instance = super(MLService, cls).__new__(cls)
            cls._instance._initialize()
        return cls._instance

    def _initialize(self):
        # Look for model file
        loaded = False
        for path in settings.MODEL_LOCATIONS:
            if path and path.is_file():
                try:
                    logger.info(f"Attempting to load model from: {path}")
                    # Suppress threadpool warning if needed
                    os.environ["OMP_NUM_THREADS"] = "1"
                    model = joblib.load(str(path))
                    self._model = model
                    self._model_path_used = str(path)
                    self._model_type = type(model).__name__
                    if hasattr(model, "classes_"):
                        self._classes = list(model.classes_)
                    self._is_fallback = False
                    logger.info(f"Successfully loaded {self._model_type} from {path}. Classes: {self._classes}")
                    loaded = True
                    break
                except Exception as exc:
                    logger.warning(f"Failed to load model from {path}: {exc}")

        if not loaded:
            logger.warning("No pre-trained model found or failed to load. Initializing transparent rule-based fallback.")
            self._model = None
            self._model_type = "EnvironmentalBenchmarkFallbackClassifier"
            self._is_fallback = True

    @property
    def is_loaded(self) -> bool:
        return self._model is not None

    @property
    def model_type(self) -> str:
        return self._model_type

    @property
    def is_fallback(self) -> bool:
        return self._is_fallback

    @property
    def classes(self) -> list:
        return self._classes

    def validate_inputs(self, values: Dict[str, float]) -> Dict[str, float]:
        """Validate that all 6 features exist, are numeric, finite, and non-negative."""
        validated = {}
        for feature in FEATURE_NAMES:
            if feature not in values:
                raise ValueError(f"Missing required pollutant: '{feature}'")
            raw_val = values[feature]
            try:
                val = float(raw_val)
            except (ValueError, TypeError):
                raise ValueError(f"Pollutant '{feature}' must be a numeric value, got '{raw_val}'")
            if math.isnan(val) or math.isinf(val):
                raise ValueError(f"Pollutant '{feature}' cannot be NaN or Infinite")
            if val < 0.0:
                raise ValueError(f"Pollutant '{feature}' cannot be negative (got {val})")
            validated[feature] = val
        return validated

    def predict(self, values: Dict[str, float]) -> Dict[str, Any]:
        """Run air quality prediction given 6 pollutant inputs."""
        cleaned_inputs = self.validate_inputs(values)

        if self._model is not None and not self._is_fallback:
            try:
                # Prepare 2D DataFrame with identical feature column names
                input_df = pd.DataFrame(
                    [[cleaned_inputs[col] for col in FEATURE_NAMES]],
                    columns=FEATURE_NAMES
                )
                pred_label = str(self._model.predict(input_df)[0])

                probabilities = {}
                confidence = 100.0
                if hasattr(self._model, "predict_proba"):
                    proba_raw = self._model.predict_proba(input_df)[0]
                    classes = getattr(self._model, "classes_", self._classes)
                    for cls_name, p in zip(classes, proba_raw):
                        probabilities[str(cls_name)] = round(float(p) * 100, 2)
                    confidence = probabilities.get(pred_label, max(probabilities.values()))
                else:
                    probabilities = {c: (100.0 if c == pred_label else 0.0) for c in self._classes}

                return {
                    "category": pred_label,
                    "probabilities": probabilities,
                    "confidence_pct": confidence,
                    "input_values": cleaned_inputs,
                    "model_name": Path(self._model_path_used).name if self._model_path_used else "greenair_model.pkl",
                    "model_type": self._model_type,
                    "is_fallback": False,
                    "disclaimer": REGULATORY_DISCLAIMER,
                    "health_guidance": HEALTH_GUIDANCE.get(pred_label, "Follow local environmental advice."),
                    "status_color": STATUS_COLORS.get(pred_label, "#10b981"),
                }
            except Exception as e:
                logger.error(f"Error during ML model inference: {e}. Falling back to benchmark classifier.")

        # Fallback heuristic calculation
        return self._fallback_classify(cleaned_inputs)

    def _fallback_classify(self, inputs: Dict[str, float]) -> Dict[str, Any]:
        """
        Deterministic, transparent environmental threshold classifier.
        Used only if ML model file is unavailable or incompatible.
        Never pretends to be an ML model.
        """
        pm25 = inputs["PM2.5"]
        pm10 = inputs["PM10"]
        no2 = inputs["NO2"]
        co = inputs["CO"]
        so2 = inputs["SO2"]
        o3 = inputs["O3"]

        # Scaled severity scoring based on ambient air thresholds
        score_pm25 = (pm25 / 60.0)
        score_pm10 = (pm10 / 100.0)
        score_no2 = (no2 / 80.0)
        score_co = (co / 2.0)
        score_so2 = (so2 / 80.0)
        score_o3 = (o3 / 100.0)

        max_score = max(score_pm25, score_pm10, score_no2, score_co, score_so2, score_o3)

        if max_score < 0.6:
            category = "Satisfactory"
            probs = {"Satisfactory": 85.0, "Moderate": 12.0, "Poor": 3.0, "Very Poor": 0.0, "Severe": 0.0}
        elif max_score < 1.1:
            category = "Moderate"
            probs = {"Satisfactory": 15.0, "Moderate": 75.0, "Poor": 10.0, "Very Poor": 0.0, "Severe": 0.0}
        elif max_score < 2.0:
            category = "Poor"
            probs = {"Satisfactory": 0.0, "Moderate": 15.0, "Poor": 70.0, "Very Poor": 15.0, "Severe": 0.0}
        elif max_score < 3.2:
            category = "Very Poor"
            probs = {"Satisfactory": 0.0, "Moderate": 0.0, "Poor": 15.0, "Very Poor": 75.0, "Severe": 10.0}
        else:
            category = "Severe"
            probs = {"Satisfactory": 0.0, "Moderate": 0.0, "Poor": 0.0, "Very Poor": 15.0, "Severe": 85.0}

        return {
            "category": category,
            "probabilities": probs,
            "confidence_pct": probs[category],
            "input_values": inputs,
            "model_name": "Fallback Rule-Based Benchmark Engine",
            "model_type": "Deterministic Environmental Heuristic",
            "is_fallback": True,
            "disclaimer": (
                "Notice: Generated via deterministic ambient air quality benchmarks because the ML model was unavailable. "
                + REGULATORY_DISCLAIMER
            ),
            "health_guidance": HEALTH_GUIDANCE.get(category, "Follow local environmental advice."),
            "status_color": STATUS_COLORS.get(category, "#10b981"),
        }

ml_service = MLService()
